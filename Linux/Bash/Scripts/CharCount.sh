#!/bin/bash

# Проверяем, передан ли аргумент (путь к файлу)
if [ -z "$1" ]; then
    echo "Ошибка: Укажите путь к файлу."
    echo "Использование: $0 <путь_к_файлу>"
    exit 1
fi

FILE="$1"

# Проверяем, существует ли файл и является ли он обычным файлом
if [ ! -f "$FILE" ]; then
    echo "Ошибка: Файл '$FILE' не найден или это директория."
    exit 1
fi

# Подсчитываем строки
LINES_COUNT=$(wc -l < "$FILE")

echo "Количество строк в файле '$FILE': $LINES_COUNT"
